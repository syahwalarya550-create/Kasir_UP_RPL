private void aturTabelProduk() {

    modelProduk = new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "No",
            "ID",
            "Nama Barang",
            "Kategori",
            "Harga",
            "Stok",
            "Satuan",
            "Status Stok",
            "Aksi"
        }
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return column == 8;
        }
    };

    tabelProduk.setModel(modelProduk);

    tabelProduk.setAutoResizeMode(
        javax.swing.JTable.AUTO_RESIZE_OFF
    );

    // Pengaturan tampilan dasar
    pengaturantabel.TabelStok.atur(tabelProduk);

    // Tampilan warna dan font
    aturTampilanTabelProduk();

    // Lebar kolom
    aturLebarKolom();

    // Sembunyikan kolom ID
    tabelProduk.getColumnModel().getColumn(1).setMinWidth(0);
    tabelProduk.getColumnModel().getColumn(1).setMaxWidth(0);
    tabelProduk.getColumnModel().getColumn(1).setPreferredWidth(0);

    // Tombol Edit dan Hapus
    pengaturantabel.TombolAksi aksi =
        new pengaturantabel.TombolAksi(
            tabelProduk,
            this::editBarang,
            this::hapusBarang
        );

    tabelProduk.getColumnModel()
        .getColumn(8)
        .setCellRenderer(aksi);

    tabelProduk.getColumnModel()
        .getColumn(8)
        .setCellEditor(aksi);
}


private void aturTampilanTabelProduk() {

    // Warna utama
    Color ungu = new Color(51, 0, 102);
    Color biruMuda = new Color(220, 238, 250);
    Color biruMudaAlternatif = new Color(235, 246, 253);
    Color biruTerpilih = new Color(185, 220, 245);
    Color garis = new Color(195, 218, 235);

    // Tampilan keseluruhan tabel
    tabelProduk.setFont(
        new Font("Segoe UI", Font.PLAIN, 13)
    );

    tabelProduk.setForeground(
        new Color(35, 45, 60)
    );

    tabelProduk.setBackground(biruMuda);

    tabelProduk.setSelectionBackground(biruTerpilih);
    tabelProduk.setSelectionForeground(ungu);

    tabelProduk.setGridColor(garis);
    tabelProduk.setShowGrid(true);

    tabelProduk.setRowHeight(42);
    tabelProduk.setIntercellSpacing(
        new java.awt.Dimension(1, 1)
    );

    tabelProduk.setFillsViewportHeight(true);

    // Header tabel
    JTableHeader header = tabelProduk.getTableHeader();

    header.setPreferredSize(
        new java.awt.Dimension(0, 43)
    );

    header.setFont(
        new Font("Segoe UI", Font.BOLD, 14)
    );

    header.setDefaultRenderer(new DefaultTableCellRenderer() {

        @Override
        public Component getTableCellRendererComponent(
            javax.swing.JTable table,
            Object value,
            boolean selected,
            boolean focused,
            int row,
            int column
        ) {

            super.getTableCellRendererComponent(
                table, value, selected, focused, row, column
            );

            setOpaque(true);
            setHorizontalAlignment(SwingConstants.CENTER);

            setBackground(ungu);
            setForeground(Color.WHITE);

            setFont(
                new Font("Segoe UI", Font.BOLD, 14)
            );

            setBorder(
                BorderFactory.createMatteBorder(
                    0, 0, 2, 1,
                    new Color(90, 55, 130)
                )
            );

            return this;
        }
    });

   
    for (int kolom = 0; kolom < 8; kolom++) {

        final int indeksKolom = kolom;

        DefaultTableCellRenderer renderer =
            new DefaultTableCellRenderer() {

            @Override
            public Component getTableCellRendererComponent(
                javax.swing.JTable table,
                Object value,
                boolean selected,
                boolean focused,
                int row,
                int column
            ) {

                super.getTableCellRendererComponent(
                    table, value, selected, focused, row, column
                );

                setOpaque(true);

                setFont(table.getFont());

                if (selected) {
                    setBackground(biruTerpilih);
                    setForeground(ungu);
                } else {
                    setBackground(
                        row % 2 == 0
                        ? biruMuda
                        : biruMudaAlternatif
                    );

                    setForeground(
                        new Color(35, 45, 60)
                    );
                }

                setBorder(
                    BorderFactory.createMatteBorder(
                        0, 0, 1, 1, garis
                    )
                );

                // Pengaturan posisi tulisan
                if (indeksKolom == 2 || indeksKolom == 3) {
                    setHorizontalAlignment(SwingConstants.LEFT);
                    setBorder(
                        BorderFactory.createCompoundBorder(
                            BorderFactory.createMatteBorder(
                                0, 0, 1, 1, garis
                            ),
                            BorderFactory.createEmptyBorder(0, 8, 0, 5)
                        )
                    );
                } else {
                    setHorizontalAlignment(SwingConstants.CENTER);
                }

                return this;
            }
        };

        tabelProduk.getColumnModel()
            .getColumn(kolom)
            .setCellRenderer(renderer);
    }

    // Warna area kosong di bawah tabel
    jScrollPane1.getViewport().setBackground(biruMuda);
    jScrollPane1.setBorder(
        BorderFactory.createLineBorder(garis, 1)
    );
}



    
    private void aturKategoriProduk() {

    Kategori.removeAllItems();

    Kategori.addItem("Semua Kategori");

    try {

        List<Produk> daftar =
                produkService.getSemuaProduk();

        java.util.Set<String> kategori =
                new java.util.TreeSet<>(
                        String.CASE_INSENSITIVE_ORDER);

        for (Produk produk : daftar) {

            if (produk.getKategori() != null
                    && !produk.getKategori().trim().isEmpty()) {

                kategori.add(produk.getKategori());
            }
        }

        for (String namaKategori : kategori) {
            Kategori.addItem(namaKategori);
        }

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Gagal memuat kategori:\n" + e.getMessage());
    }
}
    
    private void tampilkanProduk() {

    try {

        String keyword = Search.getText();

        String kategori =
                Kategori.getSelectedItem() == null
                ? "Semua Kategori"
                : Kategori.getSelectedItem().toString();

        List<Produk> daftar =
                produkService.cariProduk(
                        keyword,
                        kategori);

        modelProduk.setRowCount(0);

        NumberFormat rupiah =
                NumberFormat.getCurrencyInstance(
                        new Locale("id", "ID"));

        int nomor = 1;

        for (Produk produk : daftar) {


modelProduk.addRow(new Object[]{
    nomor++,
    produk.getId(),
    produk.getNamaProduk(),
    produk.getKategori(),
    rupiah.format(produk.getHarga()),
    produk.getStok(),
    produk.getSatuan(),
    produk.getStatusStok(),
    ""
});

        }

        TotalBarang.setText(
                produkService.getTotalBarang()
                + " Barang");

        TotalStok.setText(
                produkService.getTotalStok()
                + " Unit");

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Gagal memuat produk:\n" + e.getMessage(),
                "Kesalahan Database",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}
    
    


