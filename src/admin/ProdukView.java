private Object[] formBarang(String judul, Object[] data) {

    JTextField nama = new JTextField(
        data == null ? "" : data[0].toString()
    );

    JTextField kategori = new JTextField(
        data == null ? "" : data[1].toString()
    );

    JTextField harga = new JTextField(
        data == null ? "" : data[2].toString()
    );

    JTextField stok = new JTextField(
        data == null ? "20" : data[3].toString()
    );

    JTextField satuan = new JTextField(
        data == null ? "" : data[4].toString()
    );

    JPanel panel = new JPanel(new GridLayout(5, 2, 8, 8));

    panel.add(new javax.swing.JLabel("Nama Barang"));
    panel.add(nama);

    panel.add(new javax.swing.JLabel("Kategori"));
    panel.add(kategori);

    panel.add(new javax.swing.JLabel("Harga"));
    panel.add(harga);

    panel.add(new javax.swing.JLabel("Stok"));
    panel.add(stok);

    panel.add(new javax.swing.JLabel("Satuan"));
    panel.add(satuan);

    int hasil = JOptionPane.showConfirmDialog(
        this,
        panel,
        judul,
        JOptionPane.OK_CANCEL_OPTION,
        JOptionPane.PLAIN_MESSAGE
    );

    if (hasil != JOptionPane.OK_OPTION) {
        return null;
    }

    String namaBarang = nama.getText().trim();
    String namaKategori = kategori.getText().trim();
    String hargaBarang = harga.getText().trim();
    String stokBarang = stok.getText().trim();
    String satuanBarang = satuan.getText().trim();

    if (namaBarang.isEmpty()
            || namaKategori.isEmpty()
            || hargaBarang.isEmpty()
            || stokBarang.isEmpty()
            || satuanBarang.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Semua kolom wajib diisi!"
        );

        return null;
    }

    try {
        double nilaiHarga = Double.parseDouble(
            hargaBarang.replace(",", ".")
        );

        int nilaiStok = Integer.parseInt(stokBarang);

        if (nilaiHarga < 0 || nilaiStok < 0) {
            JOptionPane.showMessageDialog(
                this,
                "Harga dan stok tidak boleh negatif!"
            );
            return null;
        }

        return new Object[]{
            namaBarang,
            namaKategori,
            nilaiHarga,
            nilaiStok,
            satuanBarang
        };

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this,
            "Harga dan stok harus berupa angka!"
        );
        return null;
    }
}


private void tambahBarang() {

    Object[] data = formBarang("Tambah Barang", null);

    if (data == null) {
        return;
    }

    String sql = "INSERT INTO layanan "
            + "(nama_layanan, kategori, harga, stok, satuan, aktif) "
            + "VALUES (?, ?, ?, ?, ?, 1)";

    try (Connection conn = Koneksi.getKoneksi();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, data[0].toString());
        ps.setString(2, data[1].toString());
        ps.setDouble(3, (double) data[2]);
        ps.setInt(4, (int) data[3]);
        ps.setString(5, data[4].toString());

        ps.executeUpdate();

        JOptionPane.showMessageDialog(
            this,
            "Barang berhasil ditambahkan!"
        );

        aturKategoriProduk();
        tampilkanProduk();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Gagal menambahkan barang:\n" + e.getMessage(),
            "Kesalahan Database",
            JOptionPane.ERROR_MESSAGE
        );
    }
}


private void editBarang(int baris) {

    int id = Integer.parseInt(
        modelProduk.getValueAt(baris, 1).toString()
    );

    String hargaLama = modelProduk.getValueAt(baris, 4)
        .toString()
        .replaceAll("[^0-9,.]", "")
        .replace(".", "")
        .replace(",", ".");

    Object[] dataLama = {
        modelProduk.getValueAt(baris, 2),
        modelProduk.getValueAt(baris, 3),
        hargaLama,
        modelProduk.getValueAt(baris, 5),
        modelProduk.getValueAt(baris, 6)
    };

    Object[] data = formBarang("Edit Barang", dataLama);

    if (data == null) {
        return;
    }

    String sql = "UPDATE layanan SET "
            + "nama_layanan=?, kategori=?, harga=?, "
            + "stok=?, satuan=? WHERE id=?";

    try (Connection conn = Koneksi.getKoneksi();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, data[0].toString());
        ps.setString(2, data[1].toString());
        ps.setDouble(3, (double) data[2]);
        ps.setInt(4, (int) data[3]);
        ps.setString(5, data[4].toString());
        ps.setInt(6, id);

        ps.executeUpdate();

        JOptionPane.showMessageDialog(
            this,
            "Barang berhasil diperbarui!"
        );

        aturKategoriProduk();
        tampilkanProduk();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Gagal mengedit barang:\n" + e.getMessage(),
            "Kesalahan Database",
            JOptionPane.ERROR_MESSAGE
        );
    }
}


private void hapusBarang(int baris) {

    int id = Integer.parseInt(
        modelProduk.getValueAt(baris, 1).toString()
    );

    String namaBarang = modelProduk.getValueAt(baris, 2).toString();

    int pilihan = JOptionPane.showConfirmDialog(
        this,
        "Apakah kamu yakin ingin menonaktifkan barang ini?\n\n"
            + namaBarang,
        "Konfirmasi Hapus",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.WARNING_MESSAGE
    );

    if (pilihan != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "UPDATE layanan SET aktif=0 WHERE id=?";

    try (Connection conn = Koneksi.getKoneksi();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setInt(1, id);

        int hasil = ps.executeUpdate();

        if (hasil > 0) {
            JOptionPane.showMessageDialog(
                this,
                "Barang berhasil dinonaktifkan!"
            );

            aturKategoriProduk();
            tampilkanProduk();
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Gagal menonaktifkan barang:\n" + e.getMessage(),
            "Kesalahan Database",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

    
    
