private void aturTabelRiwayat() {
    modelRiwayat = new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "ID", "No", "Nomor Pesanan", "Nama Pelanggan",
            "Kelas", "Tanggal Pesanan", "Total", "Aksi"
        }
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return column == 7;
        }
    };

    tabelDaftarRiwayat.setModel(modelRiwayat);
    tabelDaftarRiwayat.setRowHeight(35);
    tabelDaftarRiwayat.setAutoCreateRowSorter(true);
    tabelDaftarRiwayat.setAutoResizeMode(
            javax.swing.JTable.AUTO_RESIZE_OFF);

    tabelDaftarRiwayat.getColumnModel().getColumn(0).setMinWidth(0);
    tabelDaftarRiwayat.getColumnModel().getColumn(0).setMaxWidth(0);
    tabelDaftarRiwayat.getColumnModel().getColumn(0).setPreferredWidth(0);
    
    // Ukuran nominal pendapatan
Pendapatan.setBounds(60, 40, 125, 25);
Pendapatan.setFont(new java.awt.Font("Segoe UI", 1, 14));

// Ukuran total pesanan
Pesanan.setBounds(70, 40, 90, 25);

// Tabel bisa digeser ke samping jika kolom tidak muat
jScrollPane1.setHorizontalScrollBarPolicy(
        javax.swing.JScrollPane.HORIZONTAL_SCROLLBAR_AS_NEEDED
);

    int[] lebar = {0, 45, 160, 150, 100, 150, 130, 170};

    for (int i = 1; i < lebar.length; i++) {
        tabelDaftarRiwayat.getColumnModel()
                .getColumn(i).setPreferredWidth(lebar[i]);
    }

    TombolAksiRiwayat tombolAksi = new TombolAksiRiwayat(
        new TombolAksiRiwayat.Aksi() {
            @Override
            public void edit(int baris) {
                editPesanan(baris);
            }

            @Override
            public void hapus(int baris) {
                hapusPesanan(baris);
            }
        }
    );

    tabelDaftarRiwayat.getColumnModel()
            .getColumn(7).setCellRenderer(tombolAksi);

    tabelDaftarRiwayat.getColumnModel()
            .getColumn(7).setCellEditor(tombolAksi);

    tabelDaftarRiwayat.getTableHeader().setReorderingAllowed(false);
}

    
   
private void aturFilterRiwayat() {
    PilihTahun.removeAllItems();
    PilihBulan.removeAllItems();

    PilihTahun.addItem("Semua");

    int tahunSekarang = LocalDate.now().getYear();

    for (int tahun = tahunSekarang; tahun >= tahunSekarang - 5; tahun--) {
        PilihTahun.addItem(String.valueOf(tahun));
    }

    String[] bulan = {
        "Semua", "Januari", "Februari", "Maret", "April",
        "Mei", "Juni", "Juli", "Agustus", "September",
        "Oktober", "November", "Desember"
    };

    for (String nama : bulan) {
        PilihBulan.addItem(nama);
    }

    perbaruiPilihanMinggu();
    perbaruiPilihanHari();
}

private void perbaruiPilihanMinggu() {
    Object pilihanLama = PilihMinggu.getSelectedItem();

    PilihMinggu.removeAllItems();
    PilihMinggu.addItem("Semua");

    Integer tahun = getPilihanTahun();
    Integer bulan = getPilihanBulan();

    if (tahun != null && bulan != null) {
        int jumlahHari = YearMonth.of(tahun, bulan).lengthOfMonth();
        int jumlahMinggu = (jumlahHari + 6) / 7;

        for (int i = 1; i <= jumlahMinggu; i++) {
            PilihMinggu.addItem("Minggu " + i);
        }
    } else {
        for (int i = 1; i <= 5; i++) {
            PilihMinggu.addItem("Minggu " + i);
        }
    }

    if (pilihanLama != null) {
        PilihMinggu.setSelectedItem(pilihanLama);
    }
}

private void perbaruiPilihanHari() {
    Object pilihanLama = PilihHari.getSelectedItem();

    PilihHari.removeAllItems();
    PilihHari.addItem("Semua");

    Integer tahun = getPilihanTahun();
    Integer bulan = getPilihanBulan();
    Integer minggu = getPilihanMinggu();

    int jumlahHari = 31;

    if (bulan != null) {
        int tahunHitung = tahun != null
                ? tahun
                : LocalDate.now().getYear();

        jumlahHari = YearMonth.of(tahunHitung, bulan).lengthOfMonth();

        // Jika tahun tidak dipilih, Februari bisa memiliki 29 hari.
        if (tahun == null && bulan == 2) {
            jumlahHari = 29;
        }
    }

    int mulai = 1;
    int akhir = jumlahHari;

    if (minggu != null) {
        mulai = (minggu - 1) * 7 + 1;
        akhir = Math.min(minggu * 7, jumlahHari);
    }

    for (int hari = mulai; hari <= akhir; hari++) {
        PilihHari.addItem(String.valueOf(hari));
    }

    if (pilihanLama != null) {
        PilihHari.setSelectedItem(pilihanLama);
    }
}

    
