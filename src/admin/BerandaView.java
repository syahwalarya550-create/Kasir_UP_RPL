    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
        // TODO add your handling code here:
    int konfirmasi = JOptionPane.showConfirmDialog(
            this,
            "Reset seluruh input pesanan?",
            "Konfirmasi Reset",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.QUESTION_MESSAGE
    );

    // Jika pengguna memilih Tidak, batalkan reset
    if (konfirmasi != JOptionPane.YES_OPTION) {
        return;
    }

    // Kosongkan input pelanggan
    inputNamaPelanggan.setText("");
    inputKelas.setText("");
    jTextField7.setText("");

    // Aktifkan kembali input pelanggan
    inputNamaPelanggan.setEnabled(true);
    inputKelas.setEnabled(true);
    jTextField7.setEnabled(true);

    // Kosongkan data pesanan
    pesananAktif.kosongkanDetail();
    modelPesanan.setRowCount(0);

    // Reset layanan terpilih
    layananTerpilih = null;

    // Reset jumlah pesanan
    jumlah = 1;
    JumlahPesanan.setText("1");

    // Reset total harga
    TotalHarga.setText(formatRupiah(BigDecimal.ZERO));

    // Reset status penyimpanan
    pesananTersimpan = false;
    nomorPesananTersimpan = null;
    tanggalPesananTersimpan = null;

    // Aktifkan kembali tombol Simpan
    btnSimpan.setEnabled(true);

    // Tiga tombol tetap dipertahankan dan diaktifkan kembali
    btnTambahLayanan.setEnabled(true);
    TambahkanJumlahPesanan.setEnabled(true);
    KurangkanJumlahPesanan.setEnabled(true);

    // Kosongkan pilihan layanan
    PilihLayanan.clearSelection();

    // Perbarui tampilan tabel
    TabelTampilPilihanLayanan.clearSelection();
    TabelTampilPilihanLayanan.repaint();

    // Perbarui total
    hitungUlangTotal();

    JOptionPane.showMessageDialog(
            this,
            "Input pesanan berhasil direset!",
            "Reset Berhasil",
            JOptionPane.INFORMATION_MESSAGE
    );

    }//GEN-LAST:event_btnResetActionPerformed

    private void btnCetakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCetakActionPerformed
        // TODO add your handling code here:
    if (!pesananTersimpan
            || nomorPesananTersimpan == null
            || tanggalPesananTersimpan == null) {

        JOptionPane.showMessageDialog(
                this,
                "Simpan pesanan terlebih dahulu!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Ambil nama dan kelas dari input
    String nama = inputNamaPelanggan.getText().trim();
    String kelas = inputKelas.getText().trim();

    boolean adaIdentitas =
            !nama.isEmpty() && !kelas.isEmpty();

    boolean tampilIdentitas = false;

    // JIKA NAMA DAN KELAS DIISI
    if (adaIdentitas) {

        String[] pilihan = {
            "Tambahkan Nama dan Kelas",
            "Tanpa Nama dan Kelas",
            "Batal"
        };

        int hasil = JOptionPane.showOptionDialog(
                this,
                "Apakah nama dan kelas ingin ditampilkan pada struk?",
                "Pilihan Identitas Struk",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                pilihan,
                pilihan[0]
        );

        if (hasil == 0) {
            tampilIdentitas = true;
        } else if (hasil == 1) {
            tampilIdentitas = false;
        } else {
            return;
        }
    }

    CetakStrukPDF.cetak(
            this,
            nomorPesananTersimpan,
            tanggalPesananTersimpan,
            TabelTampilPilihanLayanan,
            pesananAktif.getTotal(),
            "UNIT PRODUKSI RPL",
            "/gambar/logo_rpl.png",
            nama,
            kelas,
            tampilIdentitas
    );
    }//GEN-LAST:event_btnCetakActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
    if (pesananTersimpan) {
        JOptionPane.showMessageDialog(
                this,
                "Pesanan sudah tersimpan. Silakan reset untuk membuat pesanan baru."
        );
        return;
    }

    if (pesananAktif.getDaftarDetail().isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Tambahkan minimal satu layanan terlebih dahulu!",
                "Pesanan Kosong",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    try {
        String nama = inputNamaPelanggan.getText().trim();
        String kelas = inputKelas.getText().trim();
        String catatan = jTextField7.getText().trim();

        // Nama, kelas, dan catatan boleh kosong.
        pesananAktif.setNamaPelanggan(
                nama.isEmpty() ? null : nama
        );

        pesananAktif.setKelas(
                kelas.isEmpty() ? null : kelas
        );

        pesananAktif.setCatatan(
                catatan.isEmpty() ? null : catatan
        );

        nomorPesananTersimpan =
                pesananService.simpanPesanan(pesananAktif);

        tanggalPesananTersimpan = LocalDateTime.now();

        pesananTersimpan = true;

        btnSimpan.setEnabled(false);
        btnTambahLayanan.setEnabled(false);
        TambahkanJumlahPesanan.setEnabled(false);
        KurangkanJumlahPesanan.setEnabled(false);

        JOptionPane.showMessageDialog(
                this,
                "Pesanan berhasil disimpan!\n"
                + "Nomor Pesanan: "
                + nomorPesananTersimpan,
                "Berhasil",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Gagal menyimpan pesanan:\n"
                + e.getMessage(),
                "Kesalahan",
                JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnSimpanActionPerformed

